def main():
    if not SRC.exists():
        sys.exit("industry_source.json not found \u2014 it holds the entries this converts")
    entries = json.loads(SRC.read_text(encoding="utf-8"))

    # The species field is kept in its own file so it can be filled in batches
    # without touching 29 modules. The builder never read it, so every rebuild
    # produced points with no organism on them and silently undid the work -
    # the map only had species because the embedded seed predated this builder.
    try:
        sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
        from industry_species import SPECIES
    except Exception as _e:
        sys.exit("industry_species.py could not be read (%s). Refusing to write "
                 "points with no organism on them, which is how the species work "
                 "would be undone without anyone seeing it." % _e)

    points, missing, nospec = [], [], []
    for x in entries:
        place = PLACES.get(x["name"])
        if not place:
            missing.append(x["name"]); continue
        lat, lng, city = place
        facet = (x.get("tags") or ["seed:majors"])[0].split(":")[0]
        points.append({
            "name": x["name"],
            "source": "industry:" + facet,
            "type": FACET_TYPE.get(facet, "Industry organisation"),
            "lat": lat, "lng": lng,
            "state": city,
            "precise": False,
            "impact": 3,
            "company": x.get("company") or "",
            "size": "",
            "status": "Industry organisation",
            "phase": "post",
            "date": "",
            # An entry with no organism gets an empty list, not a guess. A
            # patent register and an index fund work on no organism at all.
            "species": SPECIES.get(x["name"], []),
            # A corporate address is a registered office. Bayer's entry is
            # Monheim am Rhein because that is where the company is registered,
            # not because that is where the work is done, and the map should say
            # so rather than let a street number imply a laboratory.
            "addr_grade": "administrative",
            "url": x["url"],
            "desc": x["desc"],
            "checked": x.get("checked", ""),
            # Carried so the index and the lens/sub filters can work off the
            # points. Before this they read trackerData, which ships empty since
            # entries became map points - so the index was blank and every lens
            # button did nothing.
            "tags": x.get("tags", []),
            "kind": x.get("kind", "structured"),
            "voice": x.get("voice", "interpretive"),
            "trust": x.get("trust", "high"),
            "skind": x.get("skind", "other"),
            "company": x.get("company") or "",
            "otype": org_type(x["name"], x.get("kind", ""), x.get("skind", "")),
        })

    print("industry points: %d" % len(points))
    if missing:
        print("  ! no coordinates for %d entries \u2014 add them to PLACES:" % len(missing))
        for m in missing:
            print("      %s" % m)

    if "--dry-run" in sys.argv:
        print("\ndry run \u2014 nothing written")
        return
    OUT.write_text(json.dumps({
        "note": ("Industry organisations as map points, one marker each. Coordinates are "
                 "headquarters or principal site at city level, so every record is "
                 "precise:false \u2014 a corporate headquarters is not where the work happens."),
        "generated": date.today().isoformat(),
        "projects": points,
    }, ensure_ascii=False, indent=1), encoding="utf-8")
    print("\nwrote %s" % OUT.name)


if __name__ == "__main__":
    main()
